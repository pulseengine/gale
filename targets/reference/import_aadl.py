#!/usr/bin/env python3
"""Add every reference peripheral the AADL model does not yet carry, as Address_Only.

For each targets/<soc>.aadl: reads targets/reference/<soc>.peripherals.tsv, skips
peripherals the model already declares (by name, or by the aliases below), and writes
the rest between BEGIN/END markers -- one device type each (Base + Address_Only) and
one `periph_<name>` subcomponent on the board. Idempotent: existing blocks are
replaced. The model stays authoritative and hand-editable outside the markers;
gust-target-gen --reference cross-checks every device against the table.

usage: python3 -I targets/reference/import_aadl.py
"""
import pathlib, re

TARGETS = pathlib.Path(__file__).resolve().parent.parent
ALIASES = {"ADC1": "ADC"}  # reference name -> gale device name, as in reference.rs
BEGIN = "  -- BEGIN targets/reference import: generated by targets/reference/import_aadl.py, do not edit\n"
END = "  -- END targets/reference import\n"
SUB_BEGIN = "      -- BEGIN targets/reference import\n"
SUB_END = "      -- END targets/reference import\n"

def ident(name: str) -> str:
    return "_".join(p[:1].upper() + p[1:].lower() for p in name.split("_") if p)

def strip(text: str, a: str, b: str) -> str:
    return re.sub(re.escape(a) + r".*?" + re.escape(b), "", text, flags=re.S)

def main() -> None:
    for tsv in sorted((TARGETS / "reference").glob("*.peripherals.tsv")):
        soc = tsv.name.split(".")[0]
        aadl = TARGETS / f"{soc}.aadl"
        text = strip(strip(aadl.read_text(), BEGIN, END), SUB_BEGIN, SUB_END)
        have = {m.group(1).upper() for m in re.finditer(r"^\s*device (\w+)\s*$", text, re.M)}
        rows = []
        for line in tsv.read_text().splitlines():
            if not line or line.startswith("#"):
                continue
            name, base = line.split("\t")
            if ALIASES.get(name, name) in have:
                continue
            rows.append((name, int(base, 16)))
        types = "".join(
            f"  device {ident(n)}\n    properties\n"
            f"      Gust_Target_Props::Base         => 16#{b:08X}#;\n"
            f"      Gust_Target_Props::Address_Only => true;\n"
            f"  end {ident(n)};\n"
            for n, b in rows
        )
        subs = "".join(f"      periph_{n.lower()} : device {ident(n)};\n" for n, b in rows)
        text = re.sub(r"^(  system Board\n)", BEGIN.replace("\\", r"\\") + types + END + r"\1", text, count=1, flags=re.M)
        text = re.sub(r"^(  end Board\.\w+;\n)", SUB_BEGIN + subs + SUB_END + r"\1", text, count=1, flags=re.M)
        aadl.write_text(text)
        print(f"{soc}: {len(rows)} address-only peripherals imported, {len(have)} already modelled")

if __name__ == "__main__":
    main()
